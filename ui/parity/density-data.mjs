// Generates src/components/Timeline/densityData.ts from the canvas sheet CompDensity.dc.html
// (handoff round 10): the marks of its lane specimens in px, so the parity stories feed
// our components data whose layout must reproduce the sheet. The sheet is static
// markup (no generator), drawn for a 1212px track. Also CompR11's empty-bin lane (round 11)
// and CompAgents' Codex model calls (round 13).
//   node parity/density-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const sheet = (name) => readFileSync(here(`../../docs/ui/handoff/canvas/final/${name}`), "utf8");
const density = sheet("CompDensity.dc.html");
const r11 = sheet("CompR11.dc.html");
const agents = sheet("CompAgents.dc.html");

/** The markup of one specimen element: from its opening tag to the one that closes it. */
function specimen(spec, html = density) {
  const i = html.indexOf(`data-spec="${spec}"`);
  if (i < 0) throw new Error(`no specimen ${spec}`);
  const start = html.lastIndexOf("<", i);
  const tag = /^<(\w+)/.exec(html.slice(start))[1];
  const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, "g");
  re.lastIndex = start;
  let depth = 0;
  for (let m; (m = re.exec(html)); ) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return html.slice(start, re.lastIndex);
  }
  throw new Error(`unclosed specimen ${spec}`);
}
const num = (s) => +parseFloat(s).toFixed(2);
const prop = (st, name) => new RegExp(`(?:^|;)\\s*${name}:\\s*([^;]+)`).exec(st)?.[1]?.trim();

/** Bars (bottom-anchored): [left, width, height]. */
const bars = (seg) =>
  [...seg.matchAll(/<div style="position: absolute; bottom: 0px; left: ([\d.]+)px; width: ([\d.]+)px; height: ([\d.]+)px[^"]*">/g)].map((m) => [num(m[1]), num(m[2]), num(m[3])]);
/** Row bars (10px tall from 3px): [left, width]. */
const rowBars = (seg) => [...seg.matchAll(/top: 3px; height: 10px; left: ([\d.]+)px; width: ([\d.]+)px; background: #/g)].map((m) => [num(m[1]), num(m[2])]);
/** Hatches: [left, width]. */
const hatches = (seg) => [...seg.matchAll(/top: 3px; height: 10px; left: ([\d.]+)px; width: ([\d.]+)px; background: repeating/g)].map((m) => [num(m[1]), num(m[2])]);
/** Friction marks: [left, text, weight]. */
const marks = (seg) =>
  [...seg.matchAll(/<span class="m" style="([^"]*)">([^<]*)<\/span>/g)].map((m) => [num(prop(m[1], "left")), m[2], +prop(m[1], "font-weight")]);
/** Network segments: [left, width, text | null, danger]. */
const segments = (seg) =>
  [...seg.matchAll(/<div style="position: absolute; top: 0; height: 18px; left: ([\d.]+)px; width: ([\d.]+)px; border: 1px solid (#\w+)[^"]*">(<span[^>]*>([^<]*)<\/span>)?/g)].map((m) => [
    num(m[1]),
    num(m[2]),
    m[5] ?? null,
    m[3] === "#ff7a6b",
  ]);
/** A row specimen inside a lane. */
const row = (seg, spec) => {
  const i = seg.indexOf(`data-spec="${spec}"`);
  const j = seg.indexOf('data-spec="', i + 20);
  return seg.slice(i, j < 0 ? undefined : j);
};
const sub = (seg) => /<div class="sub">([^<]*)</.exec(seg)?.[1] ?? null;

const presence = specimen("Lane/presenceRows");
const focus = specimen("Lane/focusRows");
const device = specimen("Lane/deviceSleepRow");
const friction = specimen("Lane/frictionSplit");
const gapLane = specimen("Lane/modelCallsWithGapRow");
const data = {
  presence: {
    focused: rowBars(row(presence, "PresenceRow/focused")),
    away: rowBars(row(presence, "PresenceRow/away")),
    asleep: rowBars(row(presence, "PresenceRow/asleep")),
  },
  focus: { focused: rowBars(row(focus, "FocusRow/focused")), blurred: rowBars(row(focus, "FocusRow/blurred")) },
  device: { asleep: rowBars(row(device, "DeviceRow/asleep")) },
  network: segments(specimen("Lane/networkRow")),
  friction: {
    frustrated: marks(row(friction, "FrictionRow/frustrated")),
    interrupted: marks(row(friction, "FrictionRow/interrupted")),
    destructive: marks(row(friction, "FrictionRow/destructive")),
  },
  gapLane: { bars: bars(gapLane), gaps: hatches(gapLane), label: /class="rl"[^>]*>([^<]*)</.exec(gapLane)?.[1], sub: sub(gapLane) },
  // CompR11 (round 11): the model calls lane under an empty bin's hover, on a 1210px track.
  emptyBin: { bars: bars(specimen("Lane/modelCallsEmptyBin", r11)) },
  // CompAgents (round 13): a Codex thread's model calls per 15 s, on a 1210px track.
  codexModelCalls: { bars: bars(specimen("Lane/codexModelCalls", agents)), sub: sub(specimen("Lane/codexModelCalls", agents)) },
  modelCalls: Object.fromEntries(
    ["Lane/modelCalls24h", "Lane/modelCalls7d", "Lane/modelCalls14d", "Lane/modelCallsGrid14d", "Lane/modelCallsGrid24h"].map((s) => {
      const seg = specimen(s);
      return [s.split("/")[1], { bars: bars(seg), sub: sub(seg) }];
    }),
  ),
};

const out = `// Generated by parity/density-data.mjs from the canvas sheet CompDensity.dc.html (handoff
// round 10): its lane specimens' marks in px on a 1212px track. Do not edit by hand.
export const DENSITY = ${JSON.stringify(data, null, 0)} as const;
`;
writeFileSync(here("../src/components/Timeline/densityData.ts"), out);
