#!/bin/sh
# initdb.sh — the local Postgres's first start (docker-compose.yml): the image's entrypoint has
# created the aintercept database (built-in C.UTF-8 locale, POSTGRES_INITDB_ARGS); this creates the
# two logins in it (aintercept/internal/pg/logins.sql) with the passwords scripts/up.sh generated.
set -eu
: "${AINTERCEPT_PG_WORKER_PASSWORD:?generated by scripts/up.sh into .env}"
: "${AINTERCEPT_PG_API_PASSWORD:?generated by scripts/up.sh into .env}"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  -v worker_password="$AINTERCEPT_PG_WORKER_PASSWORD" -v api_password="$AINTERCEPT_PG_API_PASSWORD" \
  -f /aintercept/logins.sql
